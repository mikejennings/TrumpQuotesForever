#!/usr/bin/env python3
"""Validate install assets and publish a GitHub release draft."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile
import zipfile

import quote_tools as qt


def validate_archive(path, version, interface):
    with zipfile.ZipFile(path) as archive:
        if archive.testzip():
            raise ValueError('Corrupt release ZIP')
        files = {}
        for item in archive.infolist():
            if item.is_dir():
                continue
            if not item.filename.startswith('TrumpQuotesForever/') or '..' in Path(item.filename).parts:
                raise ValueError('Invalid addon archive layout')
            files[item.filename] = archive.read(item)
        qt.privacy_check(files)
        toc = files['TrumpQuotesForever/TrumpQuotesForever.toc'].decode()
        if (f'## Version: {version}\n' not in toc or f'## Interface: {interface}\n' not in toc
                or 'TrumpQuotesForever/REVIEW_ONLY.txt' in files):
            raise ValueError('Release version/interface mismatch or unapproved review archive')
        if re.search(rb'mikejennings|mike\s+jennings', b'\n'.join(files.values()), re.I):
            raise ValueError('Personal maintainer identifier found in package')



def publish(tag):
    match = re.fullmatch(r'v(\d+\.\d+\.\d+)', tag)
    if not match:
        raise ValueError('Expected a numeric vX.Y.Z release tag')
    version = match[1]
    release = json.loads(subprocess.check_output(
        ['gh', 'release', 'view', tag, '--json', 'isDraft,assets'], text=True))
    filename = f'TrumpQuotesForever-{version}.zip'
    required = {filename, filename + '.sha256', 'release.json'}
    if not required.issubset({a['name'] for a in release['assets']}):
        raise ValueError('Missing install ZIP, checksum or Forever metadata asset')
    with tempfile.TemporaryDirectory() as directory:
        folder = Path(directory)
        for name in sorted(required):
            subprocess.run(['gh', 'release', 'download', tag, '--pattern', name, '--dir', directory], check=True)
        archive = folder / filename
        digest = hashlib.sha256(archive.read_bytes()).hexdigest()
        if (folder / (filename + '.sha256')).read_text().split() != [digest, filename]:
            raise ValueError('Release ZIP does not match its SHA-256 file')
        validate_archive(archive, version, 16001)
        metadata = json.loads((folder / 'release.json').read_text())
        # Compare the complete metadata against the bundle generated by our packager.
        if metadata != {'releases': [{'name': 'TrumpQuotesForever', 'version': version,
                                      'filename': filename, 'nolib': False,
                                      'metadata': [{'flavor': 'forever', 'interface': 16001}]}]}:
            raise ValueError('Forever metadata does not match the verified install ZIP')
        if release['isDraft']:
            subprocess.run(['gh', 'release', 'edit', tag, '--draft=false', '--latest'], check=True)
            print('GitHub release published with verified install assets')
        else:
            print('GitHub release is already published; assets verified without changes')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--tag', required=True)
    args = parser.parse_args()
    try:
        publish(args.tag)
    except (ValueError, KeyError, TypeError) as error:
        parser.exit(1, f'ERROR: {error}\n')
